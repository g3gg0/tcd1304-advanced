"""Generate firmware provenance without requiring Git on source-archive builds."""

import datetime
import json
import os
from pathlib import Path
import re
import subprocess

MAX_INFO_BYTES = 1024


def git_output(project, *args):
    try:
        result = subprocess.run(
            ["git", "-C", str(project), *args],
            capture_output=True, text=True, encoding="utf-8", errors="replace",
            check=False, timeout=10,
        )
        return result.stdout.strip() if result.returncode == 0 else None
    except (OSError, subprocess.TimeoutExpired):
        return None


def compiler_version(compiler):
    if not compiler:
        return None
    try:
        result = subprocess.run(
            [compiler, "-dumpfullversion"], capture_output=True, text=True,
            check=False, timeout=10,
        )
        return result.stdout.strip()[:80] if result.returncode == 0 else None
    except (OSError, subprocess.TimeoutExpired):
        return None


def collect(project, *, version="1.2.0", board="unknown", mcu="unknown",
            environment="unknown", cpu_hz=0, compiler=None):
    project = Path(project)
    epoch = os.environ.get("SOURCE_DATE_EPOCH")
    built = (datetime.datetime.fromtimestamp(int(epoch), datetime.timezone.utc)
             if epoch is not None else datetime.datetime.now(datetime.timezone.utc))
    commit = git_output(project, "rev-parse", "HEAD")
    status = git_output(project, "status", "--porcelain", "--untracked-files=normal") if commit else None
    branch = git_output(project, "rev-parse", "--abbrev-ref", "HEAD") if commit else None
    header = (project / "include" / "main.h").read_text(encoding="utf-8")
    ccd_clock = re.search(r"^\s*#define\s+CCD_fm\s+(\d+)\s*$", header, re.MULTILINE)
    return {
        "firmware": "tcd1304-advanced",
        "protocol": 1,
        "features": ["downsample-v1", "sample-encoding-v1"],
        "max_downsample": 64, "pixels": 3694, "adc_bits": 12,
        "version": str(version)[:48],
        "built_at": built.strftime("%Y-%m-%dT%H:%M:%SZ"),
        "build_timezone": "UTC",
        "commit": commit,
        "describe": (git_output(project, "describe", "--tags", "--always") or "")[:120] or None,
        "branch": branch[:120] if branch else None,
        "dirty": bool(status) if status is not None else None,
        "board": str(board)[:80],
        "mcu": str(mcu)[:80],
        "environment": str(environment)[:80],
        "compiler": compiler_version(compiler),
        "cpu_hz": int(str(cpu_hz).rstrip("Ll")),
        "ccd_clock_hz": int(ccd_clock.group(1)) if ccd_clock else None,
    }


def write_header(destination, metadata):
    payload = json.dumps(metadata, ensure_ascii=True, separators=(",", ":"))
    if len(payload.encode("utf-8")) > MAX_INFO_BYTES:
        raise ValueError("Firmware build information exceeds the 1024-byte protocol limit")
    # Encode twice: the first JSON is the payload, the second is a C string literal.
    contents = ("/* Generated by tools/build_metadata.py. Do not edit. */\n"
                "#ifndef GENERATED_BUILD_INFO_H\n#define GENERATED_BUILD_INFO_H\n"
                f"#define BUILD_INFO_JSON {json.dumps(payload, ensure_ascii=True)}\n"
                "#endif\n")
    destination = Path(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    if not destination.exists() or destination.read_text(encoding="utf-8") != contents:
        destination.write_text(contents, encoding="utf-8")

