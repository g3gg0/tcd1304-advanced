"""Rebuild flash LUTs; round-half-up matches the browser/reference encoder."""
import math
from pathlib import Path


def generate():
    text = '/* Generated by tools/generate_log_encoding.py. Do not edit. */\n#ifndef LOG_ENCODING_H\n#define LOG_ENCODING_H\n#include <stdint.h>\n'
    for bits in [10, 8]:
        values = [math.floor(math.log1p(i) / math.log(4096) * ((1 << bits) - 1) + .5) for i in range(4096)]
        rows = [','.join(map(str, values[i:i+32])) for i in range(0, 4096, 32)]
        text += f'static const uint{16 if bits == 10 else 8}_t log{bits}_lut[4096] = {{\n' + ',\n'.join(rows) + '\n};\n'
    return text + '#endif\n'


if __name__ == '__main__':
    (Path(__file__).resolve().parents[1] / 'include' / 'log_encoding.h').write_text(generate(), encoding='utf-8')
